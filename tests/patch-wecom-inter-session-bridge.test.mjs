test("fake WeCom robot: a reply to an unknown req_id is refused with 846605 and recorded", () => {
  let onConnection;
  class FakeWss { constructor() {} on(event, fn) { if (event === "connection") onConnection = fn; } close() {} }
  const aibot = createFakeWeComAibot({ WebSocketServer: FakeWss });
  const ws = new EventEmitter();
  const sent = [];
  ws.send = (data) => sent.push(JSON.parse(data));
  onConnection(ws);
  const frame = (cmd, reqId, body) => ws.emit("message", Buffer.from(JSON.stringify({ cmd, headers: { req_id: reqId }, body })));
  const known = aibot.sendUserText({ userId: "u1", text: "hi" });
  frame("aibot_respond_msg", known.reqId, { msgtype: "stream", stream: { id: "s1", content: "ok", finish: true } });
  frame("aibot_respond_msg", "v-a2a:req:s_x:0", { msgtype: "stream", stream: { id: "s2", content: "no", finish: false } });
  frame("aibot_respond_msg", "made-up", { msgtype: "markdown", markdown: { content: "no" } });
  assert.equal(INVALID_REQ_ID_ERRCODE, 846605);
  assert.deepEqual(sent.filter((m) => !m.cmd).map((m) => m.errcode), [0, 846605, 846605], "acks only (the pushed callback is not an ack)");
  assert.deepEqual(aibot.respondAttempts.map((a) => [a.reqId, a.rejected]), [[known.reqId, false], ["v-a2a:req:s_x:0", true], ["made-up", true]]);
  assert.deepEqual(aibot.rejectedResponds.map((a) => a.reqId), ["v-a2a:req:s_x:0", "made-up"]);
  assert.deepEqual(aibot.respondsToUnknownReqIds().map((a) => a.reqId), ["v-a2a:req:s_x:0", "made-up"]);
  assert.deepEqual(aibot.streams().map((s) => s.id), ["s1"], "a refused reply creates no stream");
  assert.equal(aibot.proactive.length, 0);

  // Card taps: accepted by default (V's existing path), refused when asked to behave like WeCom.
  const tap = aibot.pressCard({ userId: "u1", taskId: "t", eventKey: "k" });
  frame("aibot_respond_msg", tap.reqId, { msgtype: "stream", stream: { id: "s3", content: "x", finish: true } });
  assert.equal(sent.at(-1).errcode, 0);
  let strictConnection;
  class StrictWss { on(event, fn) { if (event === "connection") strictConnection = fn; } close() {} }
  const strict = createFakeWeComAibot({ WebSocketServer: StrictWss, rejectEventReplies: true });
  const ws2 = new EventEmitter();
  const sent2 = [];
  ws2.send = (data) => sent2.push(JSON.parse(data));
  strictConnection(ws2);
  const tap2 = strict.pressCard({ userId: "u1", taskId: "t", eventKey: "k" });
  ws2.emit("message", Buffer.from(JSON.stringify({ cmd: "aibot_respond_msg", headers: { req_id: tap2.reqId }, body: { msgtype: "stream", stream: { id: "s4", content: "x" } } })));
  assert.equal(sent2.at(-1).errcode, 846605);
  assert.equal(strict.respondsToUnknownReqIds().length, 0, "an event req_id is known, just not answerable");
});
