// Read-only final configuration, release fingerprint and process audit.
import fs from 'node:fs';
import os from 'node:os';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {nativeExecutionConfig} from './native-execution-config.mjs';
const base='/srv/vlab-production-mirror/labs/instances/db91-parity';
const dir='/srv/vlab-production-mirror/labs/control/native-execution-rollout-20260911';
const read=p=>JSON.parse(fs.readFileSync(p));
const hash=b=>createHash('sha256').update(b).digest('hex');
const run=(c,a)=>execFileSync(c,a,{encoding:'utf8',timeout:20000}).trim();
assert.equal(os.hostname(),'VM-0-4-ubuntu');
const manifest=read(dir+'/manifest.json'),mode=read(dir+'/mode.json');
const original=fs.readFileSync(dir+'/original-config.json');
assert.equal(hash(original),manifest.originalSha);
assert.equal(fs.statSync(dir+'/original-config.json').mode&0o777,0o600);
const config=fs.readFileSync(manifest.configPath);assert.equal(hash(config),mode.configSha);
assert.deepEqual(JSON.parse(config),mode.variant==='native'?nativeExecutionConfig(JSON.parse(original),base):JSON.parse(original));
const current=read('/srv/vlab-production-mirror/labs/shared-workflow/current.json');assert.deepEqual(current,manifest.runtime);
const {fingerprintTree}=await import('/srv/vlab-production-mirror/labs/shared-workflow/tool/files.mjs');
const runtimeSha=fingerprintTree(base+'/runtime').sha256;assert.equal(runtimeSha,current.runtimeSha);
const unit='openclaw-vlab-production-mirror-v8.service';
const pid=Number(run('systemctl',['show',unit,'-p','MainPID','--value']));assert(pid>1);
const cgroup=run('systemctl',['show',unit,'-p','ControlGroup','--value']);
const pids=fs.readFileSync('/sys/fs/cgroup'+cgroup+'/cgroup.procs','utf8').trim().split('\n').filter(Boolean).map(Number);
const workerPids=pids.filter(p=>{try{return /production-worker\/worker\.(mjs|js)/.test(fs.readFileSync(`/proc/${p}/cmdline`,'utf8'));}catch{return false;}});
if(mode.variant==='native')assert.equal(workerPids.length,0);
const health=await fetch('http://127.0.0.1:24993/healthz',{signal:AbortSignal.timeout(5000)});assert.equal(health.status,200);
console.log(JSON.stringify({at:new Date().toISOString(),variant:mode.variant,pid,configSha:hash(config),originalSha:manifest.originalSha,runtimeSha,release:current.release,workerPids,cgroupProcessCount:pids.length,healthStatus:health.status,rollbackBackupVerified:true,productionTouched:false}));
