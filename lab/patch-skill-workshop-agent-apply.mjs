const BRIDGE_CURRENT_BEFORE = `  function current(runId) {
    const context = runs.get(runId);
    if (!context || context.signal.aborted) throw new Error("Worker native attempt is no longer active");
    return context;
  }`;

const BRIDGE_CURRENT_AFTER = `${BRIDGE_CURRENT_BEFORE}
  // ${MARKER}: a Skill Workshop experience review is scheduled inside this Worker
  // after a native turn and runs locally; it is never an IPC admission.
  function isLocalWorkshopReview(runId) {
    return typeof runId === "string" && runId.startsWith("skill-workshop-review:") && !runs.has(runId);
  }`;

const BRIDGE_PREPARE_BEFORE = `    prepare(input) {
      const c = current(input.runId);`;

const BRIDGE_PREPARE_AFTER = `    prepare(input) {
      if (isLocalWorkshopReview(input.runId)) return input;
      const c = current(input.runId);`;

const BRIDGE_BIND_BEFORE = `    bind(attempt, handle, isCurrent, applyAuthorized, applyVoiceToolOrder) {
      const c = current(attempt.runId);`;

const BRIDGE_BIND_AFTER = `    bind(attempt, handle, isCurrent, applyAuthorized, applyVoiceToolOrder) {
      if (isLocalWorkshopReview(attempt.runId)) return;
      const c = current(attempt.runId);`;

export function patchNativeAttemptBridge(source) {
  if (source.includes(MARKER)) return source;
  assert.equal(sha256(source), BRIDGE_BEFORE, `${BRIDGE_FILE} is not V's bytes`);
  let next = replaceOnce(source, BRIDGE_CURRENT_BEFORE, BRIDGE_CURRENT_AFTER, `${BRIDGE_FILE} current`);
  next = replaceOnce(next, BRIDGE_PREPARE_BEFORE, BRIDGE_PREPARE_AFTER, `${BRIDGE_FILE} prepare`);
  return replaceOnce(next, BRIDGE_BIND_BEFORE, BRIDGE_BIND_AFTER, `${BRIDGE_FILE} bind`);
}
