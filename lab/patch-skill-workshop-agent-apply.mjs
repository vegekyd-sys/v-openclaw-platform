// skill-workshop-agent-apply-v1: make Skill Workshop usable by V's own agents on
// V's 2026.9.1 db91.6 bytes.
//
// V 2026-10-26 (group oc_a59571a2, report "Skill Workshop failed"): two independent
// defects, both long-standing.
//
// 1. Agents could not apply update proposals for skills they did not create through
//    Workshop. Upstream (9.1 service-query, unchanged in 9.5 apply-transition.ts)
//    lets an agent apply an update only when an applied Workshop *create* proposal
//    claims the skill directory; everything else needs an operator (gateway/system,
//    i.e. the CLI or Control UI). Most of V's skills predate Workshop
//    (geelark-tiktok-login, geelark-open-account, creator-factory-tour, ...), so
//    `skill_workshop apply` failed with "Skill Workshop does not own this skill
//    path" and V routinely re-ran it as `openclaw skills workshop apply` through
//    exec (142 operator applies vs 73 agent applies since 2026-09). V's agent
//    already holds that operator path, so the gate only produced the detour, and on
//    10/26 V refused the detour because its system prompt forbids writing skills
//    outside skill_workshop. The patch lets an agent apply an *explicit* update
//    proposal (not an autonomous capture) for an operator-authored workspace skill.
//    Scan, evaluation, target-tree hash, lock and rollback are unchanged.
//    Composite skills (COMPOSITE.json: makaron, scene-cli) keep the gate: their
//    SKILL.md is generated by install-composites from parts/. Autonomous captures
//    (background review, foreground patch repair) keep the gate as well, so
//    self-learning still never rewrites a hand-written skill on its own.
//    OPENCLAW_V_WORKSHOP_AGENT_USER_SKILLS=0 restores upstream. An environment
//    variable, not a config key: skills.workshop is a strictObject and an unknown
//    key would fail config validation once these bytes are replaced.
//
// 2. Experience reviews of Worker-run turns always failed. The review is scheduled
//    inside the Worker process after the turn and starts a local embedded run
//    (runId "skill-workshop-review:<uuid>"). The Worker's native-attempt bridge
//    requires every embedded attempt to be an IPC admission and threw "Worker native
//    attempt is no longer active" (87 of 91 review failures on V 10/26; Worker
//    sessions had never been reviewed). The bridge now lets these local review runs
//    through prepare/bind unchanged, and the review's skill_workshop tool runs in
//    process instead of the Worker's isolated subprocess, which only forwards
//    workspace/agent/session and would drop the review's proposal-only limit,
//    one-mutation budget and origin.
//
// 3. Reviews from Codex /vds turns passed the turn's auth profile
//    ("openai:<account>") to a review on provider deepseek and failed with
//    "Auth profile ... is not configured for deepseek". The review now keeps the
//    profile only when it belongs to the review's provider.
import assert from "node:assert/strict";
import { createHash } from "node:crypto";

const sha256 = (value) => createHash("sha256").update(value).digest("hex");

export const SERVICE_QUERY_FILE = "service-query-Bt8YN8NM.js";
export const SERVICE_QUERY_BEFORE = "2d2689ef3d30db33f1af19b60ba514603e1e7849150374c75bbdb6452c3291f8";
export const OPENCLAW_TOOLS_FILE = "openclaw-tools-BODVdJQD.js";
export const OPENCLAW_TOOLS_BEFORE = "4bed21d8039c6d825e70100615329d03c2ede065249ff61a0c503e83d432a754";
export const EXPERIENCE_REVIEW_FILE = "experience-review-default-Dr4f0pMZ.js";
export const EXPERIENCE_REVIEW_BEFORE = "798e630be141634dc0c6fc42ecffcbc545e805ad2dea197394a7041dcd77d61b";
export const BRIDGE_FILE = "native-attempt-bridge.mjs";
export const BRIDGE_BEFORE = "0429d15e7793b3700b877f4ee6200eedb3f5ad484e79425935563edde958f2fa";

const MARKER = "skill-workshop-agent-apply-v1";

function replaceOnce(source, before, after, label) {
  const first = source.indexOf(before);
  assert.notEqual(first, -1, `${label}: anchor not found`);
  assert.equal(source.indexOf(before, first + before.length), -1, `${label}: anchor not unique`);
  return source.slice(0, first) + after + source.slice(first + before.length);
}

const OWNERSHIP_BEFORE = `\t\tconst operatorActor = input.eventActor?.type === "gateway" || input.eventActor?.type === "system";
\t\tif (record.kind === "update" && !operatorActor && !isWorkshopOwnedSkillDir(input.workspaceDir, record.target.skillDir, storeOptions$1(input.env))) throw new Error(\`Skill Workshop does not own this skill path: \${record.target.skillKey}\`);`;

const OWNERSHIP_AFTER = `\t\tconst operatorActor = input.eventActor?.type === "gateway" || input.eventActor?.type === "system";
\t\t// V ${MARKER}: an agent may apply its explicit update proposal for an operator-authored
\t\t// workspace skill; autonomous captures and generated composites keep the ownership gate.
\t\tconst vComposite = process.getBuiltinModule("node:fs").existsSync(path.join(record.target.skillDir, "COMPOSITE.json"));
\t\tconst vExplicitAgentUpdate = input.eventActor?.type === "agent" && record.autonomousCapture !== true && !vComposite && process.env.OPENCLAW_V_WORKSHOP_AGENT_USER_SKILLS !== "0";
\t\tif (record.kind === "update" && !operatorActor && !vExplicitAgentUpdate && !isWorkshopOwnedSkillDir(input.workspaceDir, record.target.skillDir, storeOptions$1(input.env))) throw new Error(vComposite ? \`Skill Workshop does not own this skill path: \${record.target.skillKey} is a generated composite (COMPOSITE.json); change its parts/ source and rebuild it with install-composites.\` : \`Skill Workshop does not own this skill path: \${record.target.skillKey}\`);`;

export function patchServiceQuery(source) {
  if (source.includes(MARKER)) return source;
  assert.equal(sha256(source), SERVICE_QUERY_BEFORE, `${SERVICE_QUERY_FILE} is not V's bytes`);
  return replaceOnce(source, OWNERSHIP_BEFORE, OWNERSHIP_AFTER, SERVICE_QUERY_FILE);
}

