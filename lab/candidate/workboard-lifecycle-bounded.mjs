function consumer(config) {
  const child=fork(consumerFile,[],{env:{...process.env,LIFECYCLE_CONSUMER_CONFIG:JSON.stringify(config)},stdio:['ignore','ignore','pipe','ipc']});
  let stderr='';child.stderr.on('data',b=>stderr+=b.toString());
  const ready=new Promise((resolve,reject)=>{child.on('message',m=>{if(m.type==='ready')resolve();});child.once('error',reject);child.once('exit',code=>{if(code)reject(Error(`consumer readiness exit ${code}: ${stderr.slice(-500)}`));});});
  let value;
  const result=new Promise((resolve,reject)=>{child.on('message',m=>{if(m.type==='result')value=m;});child.once('error',reject);child.once('exit',code=>code===0&&value?resolve(value):reject(Error(`consumer exit ${code}: ${stderr.slice(-500)}`)));});
  // Attach immediately; a pre-start failure must not become an unhandled rejection.
  result.catch(()=>{});
  return {child,ready,result};
}
