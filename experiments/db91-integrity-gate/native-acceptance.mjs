import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {randomUUID} from 'node:crypto';
import {performance} from 'node:perf_hooks';
import {DatabaseSync} from 'node:sqlite';
const exec = promisify(execFile);
const [core, root] = process.argv.slice(2);
assert.equal(os.hostname(), 'VM-0-4-ubuntu');
assert.equal(process.env.OPENCLAW_CONFIG_PATH, '/srv/vlab-production-mirror/labs/instances/db91-fix/state/openclaw.json');
assert(root.startsWith('/srv/vlab-production-mirror/labs/instances/db91-fix/tmp/native-gate-') && !fs.existsSync(root));
fs.mkdirSync(root, {mode: 0o700});
fs.mkdirSync(root + '/state', {mode: 0o700});
fs.mkdirSync(root + '/gate', {mode: 0o700});
fs.writeFileSync(root + '/state/openclaw.json', '{}', {mode: 0o600});
const env = {...process.env, OPENCLAW_STATE_DIR: root + '/state', OPENCLAW_CONFIG_PATH: root + '/state/openclaw.json', OPENCLAW_DB91_INTEGRITY_ENABLE: '0'};
delete env.OPENCLAW_DB91_INTEGRITY_DIR; delete env.OPENCLAW_DB91_INTEGRITY_EPOCH;
const client = fileURLToPath(new URL('./native-client.mjs', import.meta.url));
async function open(mode, clientEnv) {
  const r = await exec(process.execPath, ['--max-old-space-size=256', client, core, root, mode], {env: clientEnv, timeout: 90000, maxBuffer: 1024 * 1024});
  return JSON.parse(r.stdout.trim().split('\n').at(-1));
}
const created = await open('create', env);
const nativeCold = await Promise.all([open('read', env), open('read', env)]);
env.OPENCLAW_DB91_INTEGRITY_DIR = root + '/gate'; env.OPENCLAW_DB91_INTEGRITY_EPOCH = randomUUID();
const dist = path.join(core, 'dist');
const {runPreflight} = await import(pathToFileURL(path.join(dist, 'db91-integrity-bootstrap.mjs')).href);
const gate = await import(pathToFileURL(path.join(dist, 'db91-integrity-gate.mjs')).href);
const filename = root + '/state/agents/db91synthetic/agent/openclaw-agent.sqlite';
const targets = [{kind: 'agent', label: 'synthetic native schema fixture', path: filename}];
const at = performance.now();
const verified = await runPreflight(path.join(dist, 'state/openclaw-database-verify.worker.js'), targets, {env, timeoutMs: 90000});
assert(verified[0].db91Verification, 'native verifier must return proof for original database');
const preflightMs = performance.now() - at;
const reused = [];
for (let wave = 0; wave < 3; wave++) reused.push(...await Promise.all([open('read', env), open('read', env)]));
for (const r of reused) {assert.equal(r.stats.full, 0); assert(r.stats.reused >= 1);}
gate.invalidateVerification(filename, {env, reason: 'native-acceptance'});
const revalidated = await open('read', env);
assert.equal(revalidated.stats.full, 1);
const db = new DatabaseSync(filename);
db.exec('PRAGMA foreign_keys=OFF; INSERT INTO db91_fixture_child VALUES(2,999999)'); db.close();
gate.invalidateVerification(filename, {env, reason: 'synthetic-fk-damage'});
await assert.rejects(runPreflight(path.join(dist, 'state/openclaw-database-verify.worker.js'), targets, {env, timeoutMs: 90000}), /rejected/);
await assert.rejects(open('read', env), /./);
const repair = new DatabaseSync(filename); repair.exec('DELETE FROM db91_fixture_child WHERE id=2'); repair.close();
await runPreflight(path.join(dist, 'state/openclaw-database-verify.worker.js'), targets, {env, timeoutMs: 90000});
const recovery = await open('read', env);
assert.equal(recovery.stats.full, 0);
const report = {at: new Date().toISOString(), root, syntheticOnly: true, maxConcurrentClients: 2, created, nativeCold, preflightMs, reused, revalidated, foreignKeyDamageRejected: true, recovery};
fs.writeFileSync(root + '/report.json', JSON.stringify(report, null, 2));
console.log(JSON.stringify(report, null, 2));
