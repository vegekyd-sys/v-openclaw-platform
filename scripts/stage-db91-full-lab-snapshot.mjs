const evidence = {at: new Date().toISOString(), source, target, bytes: before.size, sha256: sourceSha, originalUnchanged: true, sourceHasNoOpenProcessOrSidecars: true, contentsExported: false};
fs.writeFileSync(targetRoot + '/source-manifest.json', JSON.stringify(evidence, null, 2), {mode: 0o600});
execFileSync('chown', ['-R', manifest.user + ':' + manifest.user, targetRoot]);
