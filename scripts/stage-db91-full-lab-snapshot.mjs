import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {execFileSync, spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
const root = '/srv/vlab-production-mirror/labs/instances/db91-fix';
const source = '/srv/vlab-production-mirror/generations/candidate-official-update-final-20260902/tmp/makaron-agent.before-auth-refresh.sqlite';
const targetRoot = root + '/tmp/full-native-v1';
assert.equal(os.hostname(), 'VM-0-4-ubuntu'); assert.equal(process.getuid(), 0);
const manifest = JSON.parse(fs.readFileSync('/srv/vlab-production-mirror/labs/control/db91-fix.json'));
assert.equal(manifest.owner, 'codex-db91-contention-20260907'); assert.equal(manifest.root, root);
assert.equal(execFileSync('systemctl', ['show', manifest.unit, '-p', 'MainPID', '--value'], {encoding: 'utf8'}).trim(), '0');
assert(!fs.existsSync(targetRoot)); assert.equal(fs.realpathSync(source), source);
const usage = spawnSync('fuser', [source]); assert.equal(usage.status, 1, 'snapshot is in use or cannot be checked');
for (const suffix of ['-wal', '-shm', '-journal']) assert(!fs.existsSync(source + suffix));
const before = fs.statSync(source); assert(before.isFile() && before.size === 2523619328);
const disk = fs.statfsSync(root); assert(disk.bavail * disk.bsize - before.size > 3 * 1024 ** 3 + 128 * 1024 ** 2, 'retain reserve plus limited WAL headroom');
