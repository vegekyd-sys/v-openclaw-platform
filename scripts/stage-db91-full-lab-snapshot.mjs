const target = agentDir + '/openclaw-agent.sqlite';
fs.copyFileSync(source, target, fs.constants.COPYFILE_EXCL);
fs.chmodSync(target, 0o600);
const hash = async filename => {const h = createHash('sha256'); for await (const chunk of fs.createReadStream(filename)) h.update(chunk); return h.digest('hex');};
const sourceSha = await hash(source); assert.equal(await hash(target), sourceSha);
const after = fs.statSync(source);
for (const key of ['size', 'mtimeMs', 'ctimeMs', 'ino', 'dev']) assert.equal(after[key], before[key], 'original changed while copying');
assert.equal(spawnSync('fuser', [source]).status, 1);
