import fs from 'node:fs';
import os from 'node:os';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {patchController,parityResources} from '../lab/parity-resource-profile.mjs';
assert.equal(os.hostname(),'VM-0-4-ubuntu');assert.equal(process.getuid(),0);
const root='/srv/vlab-production-mirror/labs',control=root+'/control';
const read=p=>JSON.parse(fs.readFileSync(p));
const m=read(control+'/db91-parity.json');
parityResources(m,read(control+'/integration.json'));
assert.equal(execFileSync('systemctl',['show',m.unit,'-p','MainPID','--value'],{encoding:'utf8'}).trim(),'0');
const file=control+'/labctl.mjs',source=fs.readFileSync(file,'utf8'),patched=patchController(source);
const helper=fs.readFileSync(new URL('../lab/parity-resource-profile.mjs',import.meta.url));
const helperFile=control+'/parity-resource-profile.mjs';
if(fs.existsSync(helperFile))assert(fs.readFileSync(helperFile).equals(helper));
else fs.writeFileSync(helperFile,helper,{mode:0o644,flag:'wx'});
const backup=m.root+'/tmp/labctl-before-parity.mjs';
fs.writeFileSync(backup,source,{mode:0o600,flag:'wx'});
const pending=control+'/labctl-parity.pending.mjs';
fs.writeFileSync(pending,patched,{mode:0o755,flag:'wx'});
execFileSync(process.execPath,['--check',pending]);
assert.equal(fs.readFileSync(file,'utf8'),source,'Concurrent controller modification');
fs.renameSync(pending,file);
console.log(JSON.stringify({backup,sha256:createHash('sha256').update(patched).digest('hex'),defaultsUnchanged:true,exception:m.name}));
