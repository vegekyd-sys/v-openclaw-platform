import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import {execFileSync} from 'node:child_process';
const root = '/srv/vlab-production-mirror/labs/instances/db91-fix';
const [enabled] = process.argv.slice(2);
assert(['0', '1'].includes(enabled));
assert.equal(os.hostname(), 'VM-0-4-ubuntu');
assert.equal(process.getuid(), 0);
const manifest = JSON.parse(fs.readFileSync('/srv/vlab-production-mirror/labs/control/db91-fix.json'));
assert.equal(manifest.owner, 'codex-db91-contention-20260907');
assert.equal(manifest.root, root);
assert.equal(execFileSync('systemctl', ['show', manifest.unit, '-p', 'MainPID', '--value'], {encoding: 'utf8'}).trim(), '0');
assert.equal(fs.realpathSync(root + '/state'), root + '/state');
const filename = root + '/secrets.env';
const prior = fs.readFileSync(filename, 'utf8');
fs.writeFileSync(root + '/tmp/db91-env-backup-' + Date.now(), prior, {mode: 0o600, flag: 'wx'});
const lines = prior.split('\n').filter(l => !/^OPENCLAW_DB91_INTEGRITY_/.test(l));
lines.push('OPENCLAW_DB91_INTEGRITY_ENABLE=' + enabled, 'OPENCLAW_DB91_INTEGRITY_STATE_ROOT=' + root + '/state');
fs.writeFileSync(filename, lines.join('\n') + '\n', {mode: 0o600});
console.log(JSON.stringify({owner: manifest.owner, root, gateEnabled: enabled === '1', gatewayStopped: true}));
